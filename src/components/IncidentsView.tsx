import React, { useState } from 'react';
import { Incident } from '../types';
import { INCIDENTS_DATA } from '../data/mockData';

interface IncidentsViewProps {
  onShowToast: (message: string) => void;
  onViewTrace: (spanId: string) => void;
}

export const IncidentsView: React.FC<IncidentsViewProps> = ({ onShowToast, onViewTrace }) => {
  const [incidents, setIncidents] = useState<Incident[]>(INCIDENTS_DATA);
  const [selectedIncidentId, setSelectedIncidentId] = useState<string>('1');
  const [filterTab, setFilterTab] = useState<'active' | 'resolved' | 'all'>('active');
  const [searchQuery, setSearchQuery] = useState('');
  const [isRemediating, setIsRemediating] = useState(false);

  const selectedIncident: Incident =
    incidents.find((inc) => inc.id === selectedIncidentId) || incidents[0];

  const handleSelectIncident = (id: string) => {
    setSelectedIncidentId(id);
  };

  const handleAcknowledge = () => {
    setIncidents((prev) =>
      prev.map((inc) => {
        if (inc.id === selectedIncident.id) {
          return { ...inc, acknowledged: !inc.acknowledged };
        }
        return inc;
      })
    );
    onShowToast(`Incident ${selectedIncident.code} acknowledged.`);
  };

  const handleTriggerRemediation = () => {
    setIsRemediating(true);
    onShowToast(`Executing autonomous remediation job for ${selectedIncident.service}...`);

    setTimeout(() => {
      setIsRemediating(false);
      onShowToast(`Remediation job completed: ${selectedIncident.service} restored to nominal state.`);
    }, 2500);
  };

  const handleExportPostMortem = () => {
    const postMortemContent = `# Post-Mortem: ${selectedIncident.code} - ${selectedIncident.title}
**Date & Time:** 2026-10-05T14:22:00Z
**Service:** ${selectedIncident.service}
**Severity:** ${selectedIncident.severity}
**Status:** ${selectedIncident.state}

## Incident Summary
${selectedIncident.rootCause}

## Technical Breakdown
${selectedIncident.explanation.replace(/<[^>]*>?/gm, '')}

## Correlated Telemetry
- Span ID: ${selectedIncident.spanId}
- Endpoint: ${selectedIncident.correlatedEndpoint}
- Impact Latency: ${selectedIncident.correlatedLatency}
- Origin: ${selectedIncident.origin}

## Timeline
${selectedIncident.timeline.map((t) => `- [${t.time}] ${t.title}: ${t.description}`).join('\n')}

---
Generated by TraceMind AI Autonomous Observability Platform.
`;

    const blob = new Blob([postMortemContent], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${selectedIncident.code}-post-mortem.md`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);

    onShowToast(`Post-mortem exported (${selectedIncident.code}-post-mortem.md)`);
  };

  // Filtered incidents
  const filteredIncidents = incidents.filter((inc) => {
    if (filterTab === 'active' && inc.severity === 'RESOLVED') return false;
    if (filterTab === 'resolved' && inc.severity !== 'RESOLVED') return false;
    if (searchQuery.trim()) {
      const q = searchQuery.toLowerCase();
      return (
        inc.code.toLowerCase().includes(q) ||
        inc.title.toLowerCase().includes(q) ||
        inc.service.toLowerCase().includes(q)
      );
    }
    return true;
  });

  return (
    <div className="flex flex-col w-full pb-8">
      {/* Top Action bar & Tab controls */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 mb-4">
        <div className="flex items-center gap-2">
          <div className="bg-[#0a0e17] p-1 flex items-center gap-1 border border-[#1c1f29]">
            <button
              onClick={() => setFilterTab('active')}
              className={`px-3 py-1 font-code-md text-[11px] transition-colors flex items-center gap-1.5 cursor-pointer ${
                filterTab === 'active'
                  ? 'bg-[#262a34] text-[#dbfcff] font-medium'
                  : 'text-[#b9cacb] hover:text-[#dfe2ef]'
              }`}
            >
              <span>Active</span>
              <span className="bg-[#0f131c] text-[#00f0ff] px-1 py-0.5 text-[9px] font-semibold">
                2
              </span>
            </button>
            <button
              onClick={() => setFilterTab('resolved')}
              className={`px-3 py-1 font-code-md text-[11px] transition-colors flex items-center gap-1.5 cursor-pointer ${
                filterTab === 'resolved'
                  ? 'bg-[#262a34] text-[#dbfcff] font-medium'
                  : 'text-[#b9cacb] hover:text-[#dfe2ef]'
              }`}
            >
              <span>Resolved</span>
              <span className="text-[#849495] text-[9px]">18</span>
            </button>
            <button
              onClick={() => setFilterTab('all')}
              className={`px-3 py-1 font-code-md text-[11px] transition-colors flex items-center gap-1.5 cursor-pointer ${
                filterTab === 'all'
                  ? 'bg-[#262a34] text-[#dbfcff] font-medium'
                  : 'text-[#b9cacb] hover:text-[#dfe2ef]'
              }`}
            >
              <span>All</span>
            </button>
          </div>

          <div className="hidden md:flex items-center gap-1.5 text-[#849495] font-code-sm text-[10px] px-2.5 py-1 bg-[#0a0e17] border border-[#1c1f29]">
            <span className="w-1.5 h-1.5 bg-[#4edea3]"></span>
            <span>CLUSTER HEALTH: STABLE</span>
          </div>
        </div>

        <div className="flex items-center gap-2">
          <div className="relative flex items-center">
            <span className="material-symbols-outlined absolute left-2 text-[#849495] text-[16px]">
              search
            </span>
            <input
              className="bg-[#0a0e17] text-[#dfe2ef] border border-[#1c1f29] font-code-sm text-[11px] pl-8 pr-3 py-1.5 focus:outline-none focus:bg-[#181b25] transition-colors w-64"
              placeholder="Filter by trace, service, tag..."
              type="text"
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
            />
          </div>
          <button className="bg-[#262a34] hover:bg-[#353943] text-[#dfe2ef] font-code-sm text-[11px] px-3 py-1.5 transition-colors flex items-center gap-1 cursor-pointer">
            <span className="material-symbols-outlined text-[14px]">tune</span>
            <span>Filters</span>
          </button>
        </div>
      </div>

      {/* Main Asymmetric Workspace Layout */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-3 items-start">
        {/* Incidents Stream (7 cols) */}
        <div className="lg:col-span-7 flex flex-col gap-2">
          {filteredIncidents.map((incident) => {
            const isSelected = selectedIncident.id === incident.id;
            return (
              <div
                key={incident.id}
                onClick={() => handleSelectIncident(incident.id)}
                className={`cursor-pointer p-4 transition-all flex flex-col gap-2 border ${
                  isSelected
                    ? 'bg-[#181b25] border-[#00dbe9]'
                    : 'bg-[#0a0e17] hover:bg-[#181b25] border-[#1c1f29]'
                }`}
              >
                <div className="flex items-start justify-between gap-2">
                  <div className="flex items-center gap-1.5 flex-wrap">
                    <span
                      className={`px-1.5 py-0.5 font-label-caps text-[9px] uppercase tracking-wider ${
                        incident.severity === 'CRITICAL'
                          ? 'bg-[#31353f] text-[#ffb4ab]'
                          : incident.severity === 'MEDIUM'
                          ? 'bg-[#262a34] text-[#4edea3]'
                          : 'bg-[#262a34] text-[#849495]'
                      }`}
                    >
                      {incident.severity}
                    </span>
                    <span className="font-code-md text-[12px] text-[#dbfcff] font-medium">
                      {incident.code}
                    </span>
                    <span className="text-[#3b494b] font-code-sm">/</span>
                    <span className="font-code-sm text-[#b9cacb] text-[11px]">
                      {incident.service}
                    </span>
                  </div>
                  <span className="font-code-sm text-[#849495] text-[10px]">
                    {incident.timeAgo}
                  </span>
                </div>

                <div className="flex flex-col gap-1">
                  <h2 className="font-headline-md text-[16px] text-[#dfe2ef] tracking-tight font-semibold">
                    {incident.title}
                  </h2>
                  <div className="flex items-start gap-1.5 bg-[#0a0e17] p-2.5 border border-[#1c1f29]">
                    <span
                      className={`material-symbols-outlined text-[16px] mt-0.5 ${
                        incident.severity === 'CRITICAL' ? 'text-[#00dbe9]' : 'text-[#4edea3]'
                      }`}
                    >
                      auto_awesome
                    </span>
                    <p className="font-body-md text-[12px] text-[#b9cacb] leading-relaxed">
                      <span
                        className={`font-code-sm text-[11px] font-semibold ${
                          incident.severity === 'CRITICAL' ? 'text-[#00dbe9]' : 'text-[#4edea3]'
                        }`}
                      >
                        Root Cause:
                      </span>{' '}
                      {incident.rootCause}
                    </p>
                  </div>
                </div>

                <div className="flex items-center justify-between pt-1">
                  <div className="flex items-center gap-3">
                    <div className="flex items-center gap-1.5">
                      <span
                        className={`w-1.5 h-1.5 ${
                          incident.state === 'INVESTIGATING'
                            ? 'bg-[#ffb4ab] animate-pulse'
                            : 'bg-[#4edea3]'
                        }`}
                      ></span>
                      <span
                        className={`font-code-sm text-[10px] uppercase tracking-wider ${
                          incident.state === 'INVESTIGATING' ? 'text-[#ffb4ab]' : 'text-[#4edea3]'
                        }`}
                      >
                        {incident.state}
                      </span>
                    </div>
                    <span className="font-code-sm text-[#849495] text-[10px]">
                      Span: {incident.spanId}
                    </span>
                  </div>
                  <span
                    onClick={(e) => {
                      e.stopPropagation();
                      onViewTrace(incident.spanId);
                    }}
                    className="font-code-sm text-[11px] text-[#dbfcff] hover:text-[#00f0ff] flex items-center gap-0.5 cursor-pointer"
                  >
                    Inspect Diagnostics{' '}
                    <span className="material-symbols-outlined text-[14px]">arrow_forward</span>
                  </span>
                </div>
              </div>
            );
          })}

          {/* Telemetry Density Feed (Resolved Summary Item) */}
          <div className="bg-[#0a0e17]/60 p-2.5 flex items-center justify-between opacity-70 border border-[#1c1f29]">
            <div className="flex items-center gap-2">
              <span className="material-symbols-outlined text-[#849495] text-[18px]">
                check_circle
              </span>
              <div className="flex flex-col">
                <span className="font-code-sm text-[#dfe2ef] text-[11px]">
                  INC-4081: TLS Handshake timeout on edge-ingress-04
                </span>
                <span className="font-code-sm text-[#849495] text-[10px]">
                  Resolved 3h ago by Auto-healer · trace: 4e9102c
                </span>
              </div>
            </div>
            <button
              onClick={() => handleSelectIncident('3')}
              className="text-[#849495] hover:text-[#dfe2ef] font-code-sm text-[10px] px-2 py-0.5 border border-[#262a34]"
            >
              Details
            </button>
          </div>
        </div>

        {/* AI Explanation Drawer / Incident Detail Panel (5 cols) */}
        <div className="lg:col-span-5 bg-[#181b25] p-4 flex flex-col gap-4 border border-[#262a34] sticky top-20 shadow-xl">
          {/* Panel Header */}
          <div className="flex flex-col gap-1 pb-2 border-b border-[#262a34]">
            <div className="flex items-center justify-between">
              <div className="flex items-center gap-1.5 font-label-caps text-[9px] uppercase text-[#dbfcff] tracking-widest">
                <span className="material-symbols-outlined text-[14px] text-[#00f0ff]">
                  psychology
                </span>
                <span>TRACEMIND DIAGNOSTIC ENGINE</span>
              </div>
              <span className="font-code-sm text-[10px] bg-[#31353f] px-1.5 py-0.5 text-[#dfe2ef]">
                {selectedIncident.code}
              </span>
            </div>
            <h3 className="font-headline-lg text-[18px] text-[#dfe2ef] font-semibold leading-snug">
              {selectedIncident.title}
            </h3>
            <div className="flex items-center gap-2 text-[#849495] font-code-sm text-[10px] pt-0.5">
              <span>Cluster: prod-us-east-2</span>
              <span>·</span>
              <span>{selectedIncident.service}</span>
            </div>
          </div>

          {/* Correlated Trace Span Micro-Chart */}
          <div className="flex flex-col gap-1">
            <div className="flex items-center justify-between font-code-sm text-[10px]">
              <span className="text-[#849495] uppercase">Correlated Trace Span</span>
              <span className="text-[#00f0ff] font-medium">{selectedIncident.spanId}</span>
            </div>
            <div className="bg-[#0a0e17] p-2.5 flex flex-col gap-1.5 border border-[#1c1f29]">
              <div className="flex justify-between font-code-sm text-[11px]">
                <span className="text-[#dfe2ef]">{selectedIncident.correlatedEndpoint}</span>
                <span className="text-[#ffb4ab] font-medium">
                  {selectedIncident.correlatedLatency}
                </span>
              </div>
              <div className="w-full bg-[#1c1f29] h-1.5 relative overflow-hidden">
                <div
                  className={`h-full ${selectedIncident.barColor} transition-all duration-500`}
                  style={{ width: selectedIncident.barWidth }}
                ></div>
              </div>
              <div className="flex justify-between font-code-sm text-[9px] text-[#849495] pt-0.5">
                <span>Origin: {selectedIncident.origin}</span>
                <span>Eviction lock: {selectedIncident.lockTime}</span>
              </div>
            </div>
          </div>

          {/* Plain-Language Diagnostic Summary */}
          <div className="flex flex-col gap-1">
            <span className="font-label-caps text-[9px] uppercase tracking-wider text-[#849495]">
              Root Cause Analysis
            </span>
            <div className="bg-[#0a0e17] p-3 text-[#dfe2ef] border border-[#1c1f29]">
              <p
                className="font-body-md text-[12px] leading-relaxed text-[#b9cacb]"
                dangerouslySetInnerHTML={{ __html: selectedIncident.explanation }}
              />
            </div>
          </div>

          {/* Visual Timeline of Trigger Events */}
          <div className="flex flex-col gap-1">
            <span className="font-label-caps text-[9px] uppercase tracking-wider text-[#849495]">
              Trigger Timeline
            </span>
            <div className="flex flex-col gap-2 pl-1 border-l border-[#262a34]">
              {selectedIncident.timeline.map((item, idx) => (
                <div key={idx} className="flex items-start gap-2 relative pl-2">
                  <div className={`w-2 h-2 ${item.color} mt-1 shrink-0`}></div>
                  <div className="flex flex-col">
                    <div className="flex items-center gap-1.5">
                      <span className="font-code-sm text-[10px] text-[#dfe2ef] font-medium">
                        {item.title}
                      </span>
                      <span className="font-code-sm text-[9px] text-[#849495]">{item.time}</span>
                    </div>
                    <span className="font-body-sm text-[11px] text-[#849495]">
                      {item.description}
                    </span>
                  </div>
                </div>
              ))}
            </div>
          </div>

          {/* High-Velocity Actions */}
          <div className="flex flex-col gap-2 pt-2 border-t border-[#262a34]">
            <div className="flex items-center gap-2">
              <button
                onClick={handleTriggerRemediation}
                disabled={isRemediating}
                className="flex-1 bg-[#dbfcff] text-[#00363a] font-code-sm text-[11px] py-2 px-3 hover:bg-[#7df4ff] transition-colors flex items-center justify-center gap-1 font-semibold cursor-pointer disabled:opacity-50"
              >
                <span className={`material-symbols-outlined text-[16px] ${isRemediating ? 'animate-spin' : ''}`}>
                  {isRemediating ? 'sync' : 'play_arrow'}
                </span>
                <span>{isRemediating ? 'Executing Script...' : selectedIncident.actionLabel}</span>
              </button>
              <button
                onClick={handleAcknowledge}
                className={`font-code-sm text-[11px] py-2 px-3 transition-colors flex items-center gap-1 cursor-pointer border ${
                  selectedIncident.acknowledged
                    ? 'bg-[#003824] text-[#4edea3] border-[#4edea3]'
                    : 'bg-[#262a34] hover:bg-[#353943] text-[#dfe2ef] border-[#3b494b]'
                }`}
              >
                <span className="material-symbols-outlined text-[16px]">task_alt</span>
                <span>{selectedIncident.acknowledged ? 'Acknowledged' : 'Acknowledge'}</span>
              </button>
            </div>
            <button
              onClick={handleExportPostMortem}
              className="w-full bg-[#0a0e17] hover:bg-[#262a34] text-[#849495] hover:text-[#dfe2ef] font-code-sm text-[10px] py-1.5 px-3 transition-colors flex items-center justify-center gap-1.5 border border-[#262a34] cursor-pointer"
            >
              <span className="material-symbols-outlined text-[14px]">description</span>
              <span>Export Post-Mortem (.md / JSON)</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
